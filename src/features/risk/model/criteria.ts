export function normalizeCriteria(content: string): string {
  return content.trim();
}

/** 저장 가능한 값이면 null, 아니면 에러 메시지. */
export function validateCriteria(content: string): string | null {
  if (content.length === 0) return '평가 기준을 입력해주세요.';
  if (content.length > CRITERIA_MAX) return `평가 기준은 ${CRITERIA_MAX}자를 넘을 수 없습니다.`;
  return null;
}
