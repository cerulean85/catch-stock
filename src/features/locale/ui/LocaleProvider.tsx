'use client';

import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from 'react';
import { getLocaleOption, LOCALE_OPTIONS, type LocaleSettings } from '@/shared/lib/locale';

const STORAGE_KEY = 'catch-stock-locale';

interface LocaleContextValue extends LocaleSettings {
  id: string;
  setLocaleId: (id: string) => void;
  t: (key: string) => string;
}

const defaultOption = LOCALE_OPTIONS[0];

const LocaleContext = createContext<LocaleContextValue>({
  id: defaultOption.id,
  locale: defaultOption.locale,
  timeZone: defaultOption.timeZone,
  setLocaleId: () => {},
  t: (key) => koMessages[key] ?? key,
});

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [localeId, setLocaleIdState] = useState(() => {
    if (typeof window === 'undefined') return defaultOption.id;
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return getLocaleOption(saved).id;
  });

  const setLocaleId = useCallback((id: string) => {
    const next = getLocaleOption(id);
    setLocaleIdState(next.id);
    window.localStorage.setItem(STORAGE_KEY, next.id);
  }, []);

  const option = getLocaleOption(localeId);

  useEffect(() => {
    document.documentElement.lang = option.locale.split('-')[0] ?? option.locale;
  }, [option.locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      id: option.id,
      locale: option.locale,
      timeZone: option.timeZone,
      setLocaleId,
      t: (key) => getMessages(option.id)[key] ?? koMessages[key] ?? key,
    }),
    [option.id, option.locale, option.timeZone, setLocaleId],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}

