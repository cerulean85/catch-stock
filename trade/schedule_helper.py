def is_holiday(d: date) -> bool:
	"""주말 또는 대한민국 공휴일 여부를 판별합니다."""
	# 1. 주말 (토요일: 5, 일요일: 6)
	if d.weekday() in (5, 6):
		return True

	# 2. holidays 라이브러리가 있을 경우
	if _KR_HOLIDAYS is not None and d in _KR_HOLIDAYS:
		return True

	# 3. 고정 양력 공휴일
	m, day = d.month, d.day
	fixed_holidays = {
		(1, 1),  # 신정
		(3, 1),  # 삼일절
		(5, 1),  # 근로자의 날 (금융기관/외환시장 휴무)
		(5, 5),  # 어린이날
		(6, 6),  # 현충일
		(8, 15),  # 광복절
		(10, 3),  # 개천절
		(10, 9),  # 한글날
		(12, 25),  # 성탄절
	}
	if (m, day) in fixed_holidays:
		return True

	# 4. 고정 양력 공휴일의 대체공휴일 (삼일절, 어린이날, 광복절, 개천절, 한글날, 성탄절이 토/일인 경우 월요일)
	# 대체공휴일 대상: (3,1), (5,5), (8,15), (10,3), (10,9), (12,25)
	if d.weekday() == 0:  # 월요일
		sun = d - timedelta(days=1)
		sat = d - timedelta(days=2)
		sub_targets = {(3, 1), (5, 5), (8, 15), (10, 3), (10, 9), (12, 25)}
		if (sun.month, sun.day) in sub_targets or (sat.month, sat.day) in sub_targets:
			return True

	# 5. 음력 명절 및 특별 대체공휴일 사전 조회
	iso = d.strftime('%Y-%m-%d')
	if iso in KNOWN_LUNAR_AND_SPECIAL_HOLIDAYS:
		return True

	return False


def is_business_day(d: date) -> bool:
	"""영업일(평일이면서 공휴일이 아닌 날) 여부를 반환합니다."""
	return not is_holiday(d)


def get_exchange_target_date(year: int, month: int) -> date:
	"""해당 연월의 환전 대상 영업일을 반환합니다.

	기본 기준일은 21일이며, 21일이 주말이나 공휴일인 경우 직전 영업일(business day)로 당깁니다.
	"""
	d = date(year, month, 21)
	while not is_business_day(d):
		d -= timedelta(days=1)
	return d


def get_previous_target_date(year: int, month: int) -> date:
	"""직전 월의 환전 대상 영업일을 반환합니다."""
	if month == 1:
		prev_year, prev_month = year - 1, 12
	else:
		prev_year, prev_month = year, month - 1
	return get_exchange_target_date(prev_year, prev_month)


def is_exchange_day(d: date) -> bool:
	"""주어진 날짜가 해당 월의 환전 실행일인지 여부를 반환합니다."""
	target = get_exchange_target_date(d.year, d.month)
	return d == target
